// 自定义分类：注册表 / sanitize / CSV 名称 / 未知分类
import {CATEGORIES,applyCats,visibleCats,catIdByName} from '../js/templates.js';
import {sanitize} from '../js/sanitize.js';
import {parseCSV,parseJSON,toCSV,toJSON} from '../js/io.js';
let p=0,f=0;const t=(n,c)=>{if(c)p++;else{f++;console.log('FAIL',n);}};
const st={cats:{custom:[{id:'c_pet',name:'宠物',icon:'home',color:'#D94545'},{id:'BAD',name:'x'},{id:'c_x',name:'<b>x',icon:'evil',color:'red'}],hidden:['car','other'],names:{doc:'我的证件'},order:['c_pet','doc']}};
applyCats(st);
t('custom added',CATEGORIES.c_pet?.name==='宠物'&&CATEGORIES.c_pet.icon==='home');
t('bad id dropped',!CATEGORIES.BAD);
t('icon/color sanitized',CATEGORIES.c_x.icon==='box'&&CATEGORIES.c_x.color==='#67717A');
t('rename builtin keeps id',CATEGORIES.doc.name==='我的证件');
t('order',Object.keys(CATEGORIES)[0]==='c_pet'&&Object.keys(CATEGORIES)[1]==='doc');
t('hidden',CATEGORIES.car.hidden&&!visibleCats().some(([k])=>k==='car'));
t('other never hidden',!CATEGORIES.other.hidden);
t('byName',catIdByName('宠物')==='c_pet'&&catIdByName('我的证件')==='doc'&&catIdByName('doc')==='doc'&&catIdByName('不存在')===null);
t('sanitize keeps custom',sanitize({name:'a',due:'2026-12-01',cat:'c_pet'}).cat==='c_pet');
t('sanitize maps name',sanitize({name:'a',due:'2026-12-01',cat:'宠物'}).cat==='c_pet');
t('sanitize keeps unknown custom id (deleted def)',sanitize({name:'a',due:'2026-12-01',cat:'c_gone'}).cat==='c_gone');
t('sanitize junk->other',sanitize({name:'a',due:'2026-12-01',cat:'<x>'}).cat==='other');
const csv=toCSV([sanitize({id:'1',name:'猫粮',due:'2026-12-01',cat:'c_pet'})]);
t('csv writes name',csv.includes('宠物')&&!csv.includes('c_pet'));
const r=parseCSV(csv);t('csv roundtrip',r.items[0].item.cat==='c_pet'&&!r.items[0].newCat);
const r2=parseCSV('名称,到期日,分类\n鱼食,2026-12-01,水族\n护照,2027-01-01,证件');
t('unknown flagged',r2.items[0].newCat==='水族'&&r2.items[0].item.cat==='other');
t('known alias not flagged',!r2.items[1].newCat);
const j=JSON.parse(toJSON([],null,st.cats.custom));t('json categories',j.categories.length===3);
t('json parse categories',parseJSON(JSON.stringify(j)).categories.length===3);
applyCats({});t('reset',!CATEGORIES.c_pet&&CATEGORIES.doc.name!=='我的证件'&&Object.keys(CATEGORIES).length===9);
console.log(`${p} passed ${f} failed`);if(f)process.exit(1);
